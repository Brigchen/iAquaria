# 构建前置脚本：把 data/www/index.html gzip 压缩并生成 src/web/www_gz.h 嵌入固件
Import("env")
import os
import gzip
import time

ROOT = os.path.join(env["PROJECT_DIR"])
SRC_HTML = os.path.join(ROOT, "data", "www", "index.html")
OUT_H = os.path.join(ROOT, "src", "web", "www_gz.h")

PLACEHOLDER = b"<html><body><h3>iAquaria</h3><p>data/www/index.html missing</p></body></html>"


def build_header():
    os.makedirs(os.path.dirname(OUT_H), exist_ok=True)
    if os.path.isfile(SRC_HTML):
        with open(SRC_HTML, "rb") as f:
            raw = f.read()
        src = "data/www/index.html"
    else:
        raw = PLACEHOLDER
        src = "PLACEHOLDER"

    gz = gzip.compress(raw, 9)

    lines = [
        "#pragma once",
        "// AUTO-GENERATED by tools/gzip_asset.py — DO NOT EDIT",
        '// source: %s  raw=%d bytes  gz=%d bytes' % (src, len(raw), len(gz)),
        "#include <pgmspace.h>",
        "",
        "const unsigned char WWW_GZ[] PROGMEM = {",
    ]
    for i in range(0, len(gz), 16):
        chunk = gz[i:i + 16]
        lines.append("    " + ",".join("0x%02X" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("const unsigned int WWW_GZ_LEN = %d;" % len(gz))
    lines.append("")

    new = "\n".join(lines)
    old = None
    if os.path.isfile(OUT_H):
        with open(OUT_H, "r", encoding="utf-8") as f:
            old = f.read()
    if new != old:  # 内容变化才写，避免无谓触发重编译
        with open(OUT_H, "w", encoding="utf-8") as f:
            f.write(new)
        print("gzip_asset: %s -> %s (gz %d bytes) %s" % (src, OUT_H, len(gz), time.strftime("%H:%M:%S")))


build_header()
